) returns uuid language plpgsql as $$
declare v_id uuid;
begin
  insert into public.questions (subject_id, topic_id, group_id, type, locale, difficulty, stem, explanation, source)
  values ((select id from public.subjects where code = p_subject), p_topic, p_group, p_type, p_locale, p_difficulty, p_stem, p_explanation, 'seed')
  returning id into v_id;
  for i in 1 .. array_length(p_options, 1) loop
    insert into public.question_options (question_id, position, content, is_correct)
    values (v_id, i, p_options[i], i = any (p_correct));
  end loop;
  return v_id;
end $$;

