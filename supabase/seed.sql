-- Көмекші функциялар (тек осы сессияда өмір сүреді)
create or replace function pg_temp.add_topic(p_subject text, p_kk text, p_ru text, p_pos int)
returns uuid language plpgsql as $$
declare v_id uuid;
begin
  insert into public.topics (subject_id, title_kk, title_ru, position)
  values ((select id from public.subjects where code = p_subject), p_kk, p_ru, p_pos)
  returning id into v_id;
  return v_id;
end $$;

create or replace function pg_temp.add_lesson(p_topic uuid, p_kk text, p_ru text, p_pos int, p_free boolean, p_summary_kk text, p_summary_ru text)
returns uuid language plpgsql as $$
declare v_id uuid;
begin
  insert into public.lessons (topic_id, title_kk, title_ru, position, is_free, duration_seconds)
  values (p_topic, p_kk, p_ru, p_pos, p_free, 600)
  returning id into v_id;
  insert into public.lesson_contents (lesson_id, summary_kk, summary_ru) values (v_id, p_summary_kk, p_summary_ru);
  return v_id;
end $$;

create or replace function pg_temp.add_q(
