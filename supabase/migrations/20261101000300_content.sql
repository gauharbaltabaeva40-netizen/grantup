-- =====================================================================
-- 3-кезең (1/3): контент — пәндер, тақырыптар, сабақтар, сұрақтар, сынақ ҰБТ варианттары.
--
-- Қорғау қағидасы:
--  * Пән/тақырып/сабақ МЕТАДЕРЕКТЕРІ (атауы, тегін/ақылы белгісі) — кірген әр оқушыға көрінеді (карта үшін).
--  * Сабақ конспектісі — тек тегін сабақта немесе толық доступта (RLS: has_full_access()).
--  * Видео ID, сұрақтар, жауап нұсқалары, дұрыс жауаптар, түсіндірмелер — API арқылы МҮЛДЕМ оқылмайды.
--    Оларды тек сервер (service_role) доступ тексергеннен кейін бір-бірлеп береді.
--    Себебі: anon кілт браузерде ашық, RLS-те select рұқсаты болса, бүкіл базаны жүктеп алуға болар еді.
-- =====================================================================

create type public.question_type as enum ('single', 'multiple');
create type public.content_locale as enum ('kk', 'ru');

-- ---------------------------------------------------------------------
-- Пәндер
-- ---------------------------------------------------------------------
create table public.subjects (
  id smallint generated by default as identity primary key,
  code text not null unique check (code ~ '^[a-z_]+$'),
  title_kk text not null,
  title_ru text not null,
  kind text not null check (kind in ('mandatory', 'profile')),
  icon text,
  color text check (color ~ '^#[0-9a-fA-F]{6}$'),
  position smallint not null default 0,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- Тақырыптар (пән ішіндегі «жол/карта» деңгейлері)
-- ---------------------------------------------------------------------
create table public.topics (
  id uuid primary key default gen_random_uuid(),
  subject_id smallint not null references public.subjects (id) on delete cascade,
  title_kk text not null,
  title_ru text not null,
  position integer not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index topics_subject_idx on public.topics (subject_id, position);
create trigger topics_updated_at before update on public.topics
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------
-- Сабақтар (метадеректер — бәріне көрінеді)
-- ---------------------------------------------------------------------
create table public.lessons (
  id uuid primary key default gen_random_uuid(),
  topic_id uuid not null references public.topics (id) on delete cascade,
  title_kk text not null,
  title_ru text not null,
  position integer not null default 0,
  is_free boolean not null default false,
  is_published boolean not null default true,
  duration_seconds integer check (duration_seconds >= 0),
  xp_reward integer not null default 20 check (xp_reward >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index lessons_topic_idx on public.lessons (topic_id, position);
create trigger lessons_updated_at before update on public.lessons
  for each row execute function public.set_updated_at();

-- Конспект (мәтін + KaTeX формулалар, Markdown) — ақылы контент
create table public.lesson_contents (
  lesson_id uuid primary key references public.lessons (id) on delete cascade,
  summary_kk text not null default '',
  summary_ru text not null default '',
  updated_at timestamptz not null default now()
);
create trigger lesson_contents_updated_at before update on public.lesson_contents
  for each row execute function public.set_updated_at();

-- YouTube видео ID — тек сервер береді (HTML-де ашық тұрмайды)
create table public.lesson_videos (
  lesson_id uuid primary key references public.lessons (id) on delete cascade,
  youtube_id text not null check (youtube_id ~ '^[A-Za-z0-9_-]{11}$'),
  updated_at timestamptz not null default now()
);

-- Сабаққа (тегін немесе толық доступ) рұқсат бар ма
create or replace function public.can_access_lesson(p_lesson uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.lessons l
    where l.id = p_lesson and l.is_published and (l.is_free or public.has_full_access())
  );
$$;
revoke execute on function public.can_access_lesson(uuid) from public, anon;
grant execute on function public.can_access_lesson(uuid) to authenticated, service_role;

-- ---------------------------------------------------------------------
-- Сұрақтар
-- ---------------------------------------------------------------------
-- Контекстік топ: бір мәтінге/суретке бірнеше сұрақ
create table public.question_groups (
  id uuid primary key default gen_random_uuid(),
  subject_id smallint not null references public.subjects (id) on delete cascade,
  topic_id uuid references public.topics (id) on delete set null,
  locale public.content_locale not null,
  title text,
  passage text not null,          -- Markdown + KaTeX
  image_path text,                -- Storage: question-images/<path>
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger question_groups_updated_at before update on public.question_groups
  for each row execute function public.set_updated_at();

create table public.questions (
  id uuid primary key default gen_random_uuid(),
  subject_id smallint not null references public.subjects (id) on delete cascade,
  topic_id uuid references public.topics (id) on delete set null,
  group_id uuid references public.question_groups (id) on delete cascade,
  type public.question_type not null default 'single',
  locale public.content_locale not null,
  difficulty smallint not null default 2 check (difficulty between 1 and 3),
  stem text not null,             -- Markdown + KaTeX ($...$, $$...$$), кесте
  image_path text,
  explanation text not null default '',
  is_active boolean not null default true,
  source text,                    -- 'manual' | 'import:<файл>' т.б.
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index questions_topic_idx on public.questions (topic_id) where is_active;
create index questions_subject_idx on public.questions (subject_id, locale) where is_active;
create index questions_group_idx on public.questions (group_id) where group_id is not null;
create trigger questions_updated_at before update on public.questions
  for each row execute function public.set_updated_at();

create table public.question_options (
  id uuid primary key default gen_random_uuid(),
  question_id uuid not null references public.questions (id) on delete cascade,
  position smallint not null,
  content text not null,          -- Markdown + KaTeX
  image_path text,
  is_correct boolean not null default false,
  unique (question_id, position)
);
create index question_options_question_idx on public.question_options (question_id);

-- ---------------------------------------------------------------------
-- Сынақ ҰБТ варианттары
-- ---------------------------------------------------------------------
create table public.mock_exams (
  id uuid primary key default gen_random_uuid(),
  title_kk text not null,
  title_ru text not null,
  locale public.content_locale not null,
  is_free boolean not null default false,
  is_published boolean not null default false,
  -- Құрастырылған кездегі құрылым (app_settings.unt_structure көшірмесі) — кейін формат өзгерсе де ескі нәтижелер дұрыс есептеледі
  structure jsonb not null,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger mock_exams_updated_at before update on public.mock_exams
  for each row execute function public.set_updated_at();

create table public.mock_exam_questions (
  mock_exam_id uuid not null references public.mock_exams (id) on delete cascade,
  question_id uuid not null references public.questions (id) on delete restrict,
  subject_id smallint not null references public.subjects (id),
  position integer not null,
  primary key (mock_exam_id, question_id),
  unique (mock_exam_id, subject_id, position)
);

-- ---------------------------------------------------------------------
-- Мамандықтар және шекті грант балдары (Грантқа дейінгі жол)
-- ---------------------------------------------------------------------
create table public.specialties (
  id uuid primary key default gen_random_uuid(),
  code text not null,                       -- мысалы, B057
  name_kk text not null,
  name_ru text not null,
  subject_pair text not null default 'math_informatics',
  threshold_score smallint not null check (threshold_score between 0 and 140),
  year smallint not null check (year between 2000 and 2100),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (code, year)
);
create trigger specialties_updated_at before update on public.specialties
  for each row execute function public.set_updated_at();

alter table public.profiles
  add column target_specialty_id uuid references public.specialties (id) on delete set null;
grant update (target_specialty_id) on public.profiles to authenticated;

-- ---------------------------------------------------------------------
-- RLS
-- ---------------------------------------------------------------------
alter table public.subjects enable row level security;
alter table public.topics enable row level security;
alter table public.lessons enable row level security;
alter table public.lesson_contents enable row level security;
alter table public.lesson_videos enable row level security;
alter table public.question_groups enable row level security;
alter table public.questions enable row level security;
alter table public.question_options enable row level security;
alter table public.mock_exams enable row level security;
alter table public.mock_exam_questions enable row level security;
alter table public.specialties enable row level security;

create policy "subjects: кірген әр адам" on public.subjects for select to authenticated using (true);

create policy "topics: жарияланған немесе админ" on public.topics for select to authenticated
  using (is_published or (select public.is_admin()));

create policy "lessons: жарияланған немесе админ" on public.lessons for select to authenticated
  using (is_published or (select public.is_admin()));

create policy "lesson_contents: тегін сабақ, толық доступ немесе админ" on public.lesson_contents
  for select to authenticated
  using (public.can_access_lesson(lesson_id) or (select public.is_admin()));

create policy "mock_exams: жарияланған немесе админ" on public.mock_exams for select to authenticated
  using (is_published or (select public.is_admin()));

create policy "specialties: кірген әр адам" on public.specialties for select to authenticated
  using (is_active or (select public.is_admin()));

-- Админ контентті API арқылы оқи алады (12-кезеңдегі редактор үшін). Оқушыларға саясат жоқ → ештеңе көрінбейді.
create policy "lesson_videos: тек админ" on public.lesson_videos for select to authenticated
  using ((select public.is_admin()));
create policy "question_groups: тек админ" on public.question_groups for select to authenticated
  using ((select public.is_admin()));
create policy "questions: тек админ" on public.questions for select to authenticated
  using ((select public.is_admin()));
create policy "question_options: тек админ" on public.question_options for select to authenticated
  using ((select public.is_admin()));
create policy "mock_exam_questions: тек админ" on public.mock_exam_questions for select to authenticated
  using ((select public.is_admin()));

-- Барлық жазу — тек сервер (service_role) арқылы, админ әрекеттері audit_log-қа жазылады
revoke insert, update, delete on
  public.subjects, public.topics, public.lessons, public.lesson_contents, public.lesson_videos,
  public.question_groups, public.questions, public.question_options,
  public.mock_exams, public.mock_exam_questions, public.specialties
from anon, authenticated;
revoke select on
  public.subjects, public.topics, public.lessons, public.lesson_contents, public.lesson_videos,
  public.question_groups, public.questions, public.question_options,
  public.mock_exams, public.mock_exam_questions, public.specialties
from anon;
